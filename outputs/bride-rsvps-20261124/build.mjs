import fs from 'node:fs/promises';
import {Workbook, SpreadsheetFile} from '/Users/faizharissa/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@oai/artifact-tool/dist/artifact_tool.mjs';
const dir = new URL('./', import.meta.url);
const {documents} = JSON.parse(await fs.readFile(new URL('rsvps-source.json', dir), 'utf8'));
const records = documents.map(d => {
 const f = d.fields;
 return [f.name?.stringValue ?? '', f.attendance?.stringValue ?? '', Number(f.guests?.integerValue ?? 0), f.updatedAt?.timestampValue ?? '', d.name.split('/').at(-1)];
}).sort((a,b)=>a[0].localeCompare(b[0]));
const attending = records.filter(r=>r[1]==='Hadir, insya-Allah');
const guests = attending.reduce((s,r)=>s+r[2],0);
console.log(JSON.stringify({records:records.length,attending:attending.length,declined:records.length-attending.length,guests}));
const wb=Workbook.create();
const s=wb.worksheets.add('Bride RSVPs');
s.getRange('A1').values=[['Bride invitation RSVPs — 24 Nov 2026']];
s.getRange('A2').values=[['Source: weddings/faiz-harissa/rsvps · timestamps shown in Malaysia time']];
s.getRange('A4:D5').values=[['Responses','Attending responses','Declined responses','Attending guests'],[records.length,attending.length,records.length-attending.length,guests]];
s.getRange('A7:E7').values=[['Name','Attendance','Guests','Updated (MYT)','Record ID']];
const rows=records.map(r=>[r[0].startsWith('=')?"'"+r[0]:r[0],r[1],r[2],r[3]?new Date(new Date(r[3]).getTime()+8*3600000):null,r[4]]);
s.getRange(`A8:E${7+rows.length}`).values=rows;
s.getRange(`D8:D${7+rows.length}`).setNumberFormat('yyyy-mm-dd hh:mm');
s.getRange(`A1:E${7+rows.length}`).format.font={name:'Arial',size:11};
for(const range of ['A4:D4','A7:E7']) s.getRange(range).format={fill:'#315C4B',font:{bold:true,color:'#FFFFFF'},rowHeight:28};
s.getRange('A1').format.font={size:18,bold:true,color:'#315C4B'};
s.getRange('A:A').format.columnWidth=40;
s.getRange('B:B').format.columnWidth=30;
s.getRange('C:C').format.columnWidth=20;
s.getRange('D:D').format.columnWidth=25;
s.getRange('E:E').format.columnWidth=34;
s.tables.add(`A7:E${7+rows.length}`,true,'BrideResponses');
s.freezePanes.freezeRows(7);
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Bride RSVPs!A4:D5',tableMaxRows:2,tableMaxCols:4})).ndjson);
const img=await wb.render({sheetName:s.name,range:'A1:D14',scale:1.5,format:'png'});
await fs.writeFile(new URL('preview.png',dir),new Uint8Array(await img.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(new URL('harissa-bride-rsvps.xlsx',dir).pathname);
